for b in book["books"]:
    for idx, c in enumerate(b["chapters"]):
        key = (b["id"], idx)
        extra = SUP.get(key, [])
        if not extra:
            continue
        if any(x.get("_add") for x in c["blocks"]):
            continue
        c["blocks"].extend(extra)
        added += 1

BOOK.write_text(json.dumps(book, ensure_ascii=False, indent=2), encoding="utf-8")
print(f"enriched chapters: {added}")
print("total blocks:", sum(len(c["blocks"]) for b in book["books"] for c in b["chapters"]))
