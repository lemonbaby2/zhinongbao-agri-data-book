def t(title, paras):
    return {"type": "text", "title": title, "paras": paras, "_add": 1}


def k(items):
    return {"type": "kpi", "items": items, "_add": 1}


def tb(title, headers, rows):
    return {"type": "table", "title": title, "headers": headers, "rows": rows, "_add": 1}


def ch(title, kind, data, note=""):
    return {"type": "chart", "title": title, "kind": kind, "data": data, "note": note, "_add": 1}


def yr(year, col, scope=None):
    v = [r[col] for r in panel if r["年份"] == year and r.get(col) is not None and (scope is None or r["省份"] == scope)]
    return sum(v) / len(v) if v else None


def fm(v, digits=1):
    return f"{v:,.{digits}f}" if isinstance(v, (int, float)) else "—"


def mac(col, year):
    for r in macro:
        if r["年份"] == year and r.get(col) is not None:
            return r[col]
    return None


