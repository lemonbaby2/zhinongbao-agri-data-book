def load(p):
    return json.load(open(p, encoding="utf-8"))


def series_slice(series, lo, hi, step=1):
    return [[int(y), v] for y, v in series if lo <= y <= hi and (int(y) - lo) % step == 0]


def at(series, year):
    d = {int(y): v for y, v in series}
    return d.get(year)


def kpi(items):
    return {"type": "kpi", "items": items}


def text(title, paras):
    return {"type": "text", "title": title, "paras": paras}


def chart(title, kind, data, note=""):
    return {"type": "chart", "title": title, "kind": kind, "data": data, "note": note}


def image(path, caption):
    return {"type": "image", "path": path, "caption": caption}


def table(title, headers, rows):
    return {"type": "table", "title": title, "headers": headers, "rows": rows}


def theme(tag, quote, question):
    """诱人深思的主题卡（阅读器新增 theme block）"""
    return {"type": "theme", "tag": tag, "quote": quote, "question": question}


